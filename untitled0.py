#1
sales=[]
while True:
    amount= float(input("Enter daily sales amount: "))

    if amount<0:
        break

    sales.append(amount)

print("Sales:", sales)


#2
sales_dict = {}

for i in range(len(sales)):
    sales_dict[i+1]= sales[i]

#3
def total_sales():
    return sum(sales)

#4
def average_sales():
    return sum(sales) / len(sales)

#5
def max_sales():
    return max(sales)


def min_sales():
    return min(sales)


print("Sales List:", sales)
print("Sales Dictionary:", sales_dict)
print("Total Sales:", total_sales())
print("Average Sales:", average_sales())
print("Maximum Sales:", max_sales())
print("Minimum Sales:", min_sales())